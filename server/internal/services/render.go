package services

import (
	"fmt"
	"strings"

	maitrev1 "github.com/Onfire7/maitre-de-serveur/server/gen/maitre/v1"
	"github.com/Onfire7/maitre-de-serveur/server/internal/quadlet/parser"
)

// One renderer for both shapes of Service (ADR 0010): a single container
// and each component of several go through the same steps, so Setup's
// overrides, network choices and Pages mean the same thing everywhere.
//
// The order matters for safety: the template is rendered, the person's
// overrides applied, and the network choice that needs a grant (the
// Node's network) written, all before the grant check reads the body
// (protectedOptions uses containerBody). Only then does the Node add its
// own lines, which are its to trust: confinement, the host name, the
// networks it manages, the Pages' ports, folders, groups and labels.

// containerBody is the [Container] body (and any other section the
// template has) of one container as the grant check sees it: the template
// rendered, overrides applied, and the network choice written.
func containerBody(spec *maitrev1.ServiceSpec, c comp, vols map[string]string, extra Extra, plan netPlan) (unit, error) {
	rendered, err := renderComponentBody(spec, c, vols)
	if err != nil {
		return nil, err
	}
	if c.Web && len(extra.Shared) > 0 {
		hosts := map[string]bool{}
		for name := range extra.Shared {
			hosts[vols[name]] = true
		}
		rendered = shareVolumes(rendered, hosts)
	}
	u := fromText(rendered, srcTemplate)
	u = applyOverrides(u, overridesFor(spec, c.Name), false)
	switch plan.kind {
	case NetworkHost:
		// The Node's own network: the template's networks and published
		// ports mean nothing there (Podman discards them).
		u = u.filterContainer(func(l line) bool {
			k, _, ok := keyValue(l.text)
			return !ok || (k != "Network" && k != "PublishPort")
		})
		u = u.appendContainer(agentLine("Network=host"))
	case NetworkTunnel:
		// Inside the Tunnel's network namespace there is no network or
		// port of its own; the Tunnel publishes its ports (planNetwork).
		u = u.filterContainer(func(l line) bool {
			k, _, ok := keyValue(l.text)
			return !ok || (k != "Network" && k != "PublishPort" && k != "HostName")
		})
	}
	return u, nil
}

// renderContainer is one container's complete unit file.
func renderContainer(spec *maitrev1.ServiceSpec, c comp, vols map[string]string, extra Extra, plan netPlan) (unit, error) {
	body, err := containerBody(spec, c, vols, extra, plan)
	if err != nil {
		return nil, err
	}
	// Read the body the way Quadlet does, so decisions below see
	// continuations and quoting correctly.
	parsed := parser.NewUnitFile()
	if err := parsed.Parse(body.String()); err != nil {
		return nil, fmt.Errorf("quadlet unit: %w", err)
	}
	container, rest := splitUnit(body)
	multi := isMulti(spec)
	var out unit
	add := func(text string) { out = append(out, agentLine(text)) }
	if multi {
		add(fmt.Sprintf("# Generated by Maître for Service %q component %q. Do not edit.", spec.GetName(), c.Name))
		add("[Unit]")
		add(fmt.Sprintf("Description=Maître Service %s (%s)", spec.GetName(), c.Name))
		add(fmt.Sprintf("PartOf=%s.target", spec.GetName()))
		for _, dep := range c.After {
			depUnit := spec.GetName() + "-" + dep + ".service"
			add("Requires=" + depUnit)
			add("After=" + depUnit)
		}
	} else {
		add(fmt.Sprintf("# Generated by Maître for Service %q (Catalog entry %q). Do not edit.", spec.GetName(), spec.GetCatalogId()))
		add("[Unit]")
		add(fmt.Sprintf("Description=Maître Service %s", spec.GetName()))
		if spec.GetInfrastructure() {
			// Infrastructure Services (DNS, DHCP) must be up before anything
			// that waits for the network.
			add("Before=network-online.target")
			add("DefaultDependencies=no")
			add("After=basic.target maitre-pool.service")
		}
	}
	if plan.kind == NetworkTunnel {
		// Lives and dies with its Tunnel: stops when it stops, and the
		// Tunnel wants it, so it starts again when the Tunnel does.
		add("BindsTo=" + plan.target + ".service")
		add("After=" + plan.target + ".service")
	}
	for _, w := range plan.wants {
		add("Wants=" + w)
	}
	add("")
	out = append(out, container...)
	if spec.GetTunnel() && !parsed.HasKey("Container", "ContainerName") {
		// The Services on a Tunnel name its container.
		add("ContainerName=" + tunnelContainer(spec.GetName()))
	}
	// Decision 189: no gaining privileges through setuid programs, unless
	// the template says otherwise (a protected option).
	if !parsed.HasKey("Container", "NoNewPrivileges") {
		add("NoNewPrivileges=true")
	}
	// The container's hostname is the Service's name (a component's, in a
	// Service of several), not Podman's random id, so apps that name
	// themselves after it (Jellyfin's server name) keep one name across
	// restarts. Not where the template names it, or shares the host's, a
	// pod's or a Tunnel's namespaces.
	onHost := lookupIs(parsed, "Network", "host")
	if plan.kind != NetworkTunnel && !parsed.HasKey("Container", "HostName") && !parsed.HasKey("Container", "Pod") && !onHost && !lookupIs(parsed, "UTS", "host") {
		if multi {
			add("HostName=" + c.Name)
		} else {
			add("HostName=" + spec.GetName())
		}
	}
	switch plan.kind {
	case NetworkTunnel:
		add("Network=container:" + tunnelContainer(plan.target))
	case NetworkHost:
	default:
		if multi {
			// The Service's own network under this component's name; the
			// web component also on maitre.network under the Service's
			// name, at the Service's address; a route out for egress
			// components of an internal Service.
			add(fmt.Sprintf("Network=%s:alias=%s", serviceNetworkUnit(spec.GetName()), c.Name))
			if c.Web {
				add(fmt.Sprintf("Network=%s:alias=%s%s", Network, spec.GetName(), ipOption(spec)))
			}
			if c.Egress && needsEgress(spec) {
				add("Network=" + egressNetworkUnit(spec.GetName()))
			}
		} else if spec.GetAddress() != "" && !onHost {
			// The template joins the shared network; the Service's
			// address goes on that line.
			out = out.mapContainer(func(l line) (line, bool) {
				if k, v, ok := keyValue(l.text); ok && k == "Network" && strings.TrimSpace(v) == Network {
					return line{"Network=" + Network + ":ip=" + spec.GetAddress(), l.source}, true
				}
				return l, true
			})
		}
		if plan.kind == NetworkService && c.Web {
			// Another Service's own network too, under this Service's name,
			// so it reaches that Service's components as the Service does.
			add(fmt.Sprintf("Network=%s:alias=%s", serviceNetworkUnit(plan.target), spec.GetName()))
		}
	}
	if c.WaitHealthy && !parsed.HasKey("Container", "Notify") {
		add("Notify=healthy")
	}
	// Each Page this container serves is published on its loopback port
	// for Caddy, the Console's proxy and the probe; not on the Node's own
	// network, where the app's port is the Node's, nor in a Tunnel, which
	// publishes for it.
	if plan.kind != NetworkTunnel && !onHost {
		for _, p := range pagesOn(spec, c) {
			if p.GetPort() != 0 && p.GetHostPort() != 0 {
				add(fmt.Sprintf("PublishPort=127.0.0.1:%d:%d", p.GetHostPort(), p.GetPort()))
			}
		}
	}
	for _, pub := range plan.publish {
		add(pub)
	}
	if c.Web {
		for _, mt := range extra.Mounts {
			opts := "z"
			if mt.ReadOnly {
				opts += ",ro"
			}
			add(fmt.Sprintf("Volume=%s:%s:%s", mt.Host, mt.Path, opts))
		}
		for _, g := range extra.Groups {
			add(fmt.Sprintf("GroupAdd=%d", g))
		}
	}
	add("Label=dev.maitre.service=" + spec.GetName())
	if multi {
		add("Label=dev.maitre.component=" + c.Name)
	}
	// A removal in Setup reaches the Node's own lines too.
	out = applyOverrides(out, overridesFor(spec, c.Name), true)
	if len(rest) > 0 {
		add("")
		out = append(out, rest...)
	}
	add("")
	add("[Service]")
	add("Restart=on-failure")
	add("RestartSec=5")
	add("TimeoutStartSec=900")
	add("")
	add("[Install]")
	if multi {
		add(fmt.Sprintf("WantedBy=%s.target", spec.GetName()))
	} else {
		add("WantedBy=multi-user.target default.target")
	}
	return out, nil
}

// ipOption is the ",ip=<address>" a web component's maitre.network line
// carries, or nothing for a Service without an address yet.
func ipOption(spec *maitrev1.ServiceSpec) string {
	if spec.GetAddress() == "" {
		return ""
	}
	return ",ip=" + spec.GetAddress()
}

// splitUnit splits a rendered body into its [Container] lines (the header
// included) and every other section after them, each without trailing
// blank lines.
func splitUnit(u unit) (container, rest unit) {
	in := true
	for _, l := range u {
		t := strings.TrimSpace(l.text)
		if strings.HasPrefix(t, "[") && strings.HasSuffix(t, "]") {
			in = t == "[Container]"
		}
		if in {
			container = append(container, l)
		} else {
			rest = append(rest, l)
		}
	}
	trim := func(u unit) unit {
		for len(u) > 0 && strings.TrimSpace(u[len(u)-1].text) == "" {
			u = u[:len(u)-1]
		}
		return u
	}
	return trim(container), trim(rest)
}

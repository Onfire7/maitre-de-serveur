package catalog

import (
	"fmt"
	"sort"
	"strings"
)

// sources are the projects whose material the Catalog may carry, with the
// notice each licence asks for (plan C11, C12).
var sources = map[string]struct{ name, url, licence string }{
	"dashboard-icons": {"dashboard-icons by Homarr Labs", "https://github.com/homarr-labs/dashboard-icons", "Apache License 2.0"},
	"selfh.st/icons":  {"selfh.st/icons by selfh.st", "https://github.com/selfhst/icons", "Creative Commons Attribution 4.0 International (CC BY 4.0)"},
	"casaos":          {"CasaOS AppStore by IceWhale Technology", "https://github.com/IceWhaleTech/CasaOS-AppStore", "Apache License 2.0"},
	"bigbear":         {"Big Bear CasaOS, Copyright (c) 2023 Big Bear Enterprises, LLC", "https://github.com/bigbeartechworld/big-bear-casaos", "MIT License"},
}

// store is the app store an entry was converted from, by its source URL;
// "compose" for a project's own file.
func store(url string) string {
	for k, s := range sources {
		if strings.HasPrefix(url, s.url+"/") {
			return k
		}
	}
	return "compose"
}

// Notice is the Catalog's NOTICE file: every icon copied from a pack and
// every entry converted from another project's file, with where it came
// from and under which licence. `make gen` writes it; CI checks it is
// current.
func Notice(idx *Index) string {
	var b strings.Builder
	b.WriteString("Maître Catalog\n\nThe Catalog is MIT licensed (see LICENSE). It also carries material from\nthe projects below, under their own licences. Generated by\n`maitre catalog-notice`; do not edit.\n")
	icons := map[string][]string{}
	converted := map[string][]string{}
	for _, e := range idx.Entries {
		s := e.Source
		if s == nil {
			continue
		}
		if s.Icon != nil {
			icons[s.Icon.Pack] = append(icons[s.Icon.Pack], fmt.Sprintf("%s: %s", e.ID, s.Icon.URL))
		}
		if s.From == "compose" || s.From == "casaos" {
			line := fmt.Sprintf("%s: converted from %s", e.ID, orUnknown(s.URL))
			if s.Licence != "" {
				line += ", " + s.Licence
			}
			converted[store(s.URL)] = append(converted[store(s.URL)], line)
		}
	}
	section := func(title string, groups map[string][]string, describe func(string) string) {
		if len(groups) == 0 {
			return
		}
		fmt.Fprintf(&b, "\n%s\n%s\n", title, strings.Repeat("=", len(title)))
		keys := make([]string, 0, len(groups))
		for k := range groups {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "\n%s\n", describe(k))
			lines := groups[k]
			sort.Strings(lines)
			for _, l := range lines {
				fmt.Fprintf(&b, "  %s\n", l)
			}
		}
	}
	describe := func(k string) string {
		if s, ok := sources[k]; ok {
			return fmt.Sprintf("%s (%s), %s:", s.name, s.url, s.licence)
		}
		return k + ":"
	}
	section("Icons", icons, describe)
	section("Converted entries", converted, func(k string) string {
		if k == "compose" {
			return "From projects' own Compose files, each under the licence named:"
		}
		return describe(k)
	})
	b.WriteString("\nEach converted entry's CONVERSION.md says what was changed from the file it\ncame from. The licences' texts are in LICENSES/.\n")
	return b.String()
}

func orUnknown(s string) string {
	if s == "" {
		return "a file of unrecorded origin"
	}
	return s
}
